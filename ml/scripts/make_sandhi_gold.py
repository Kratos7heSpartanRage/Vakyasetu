    out = os.path.join(os.path.dirname(__file__), "..", "data", "sandhi_gold.jsonl")
    with open(out, "w", encoding="utf-8") as f:
        for r in rows():
            surf = split_tokens(r["sentence"])
            assert len(surf) == len(r["tokens"]), (r["id"], surf, len(r["tokens"]))
